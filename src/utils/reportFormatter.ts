import type { JobRole, ResumeAnalysisResult } from '../types/analysis';

export function formatAnalysisReport(
  result: ResumeAnalysisResult,
  meta: { fileName: string; jobRole: JobRole }
): string {
  const lines: string[] = [
    'RESUMERANK AI — RESUME INTELLIGENCE REPORT',
    '==========================================',
    `Candidate File: ${meta.fileName}`,
    `Target Role: ${meta.jobRole}`,
    `Overall Score: ${result.overall_score}/100 (${result.verdict})`,
    `Sub-Scores: Skills ${result.skill_score}% | Experience ${result.experience_score}% | Education ${result.education_score}%`,
    '',
    'RECRUITER VERDICT',
    '-----------------',
    result.recruiter_summary,
    '',
    'MATCHED SKILLS',
    '--------------',
    ...(result.matched_skills.length > 0
      ? result.matched_skills.map((m) => `- ${m.skill}: "${m.evidence}"`)
      : ['- None identified']),
    '',
    'MISSING SKILLS',
    '--------------',
    ...(result.missing_skills.length > 0
      ? result.missing_skills.map((m) => `- [${m.importance}] ${m.skill}: ${m.reason}`)
      : ['- None identified']),
    '',
    'PARTIAL SKILLS',
    '--------------',
    ...(result.partial_skills.length > 0
      ? result.partial_skills.map((p) => `- ${p.skill}: ${p.note}`)
      : ['- None identified']),
    '',
    'ATS COMPATIBILITY ISSUES',
    '------------------------',
    ...(result.ats_issues.length > 0
      ? result.ats_issues.map((issue) => `- ${issue}`)
      : ['- No major ATS issues detected']),
    '',
    'STRENGTHS',
    '---------',
    ...result.strengths.map((s) => `- ${s}`),
    '',
    'WEAKNESSES',
    '----------',
    ...result.weaknesses.map((w) => `- ${w}`),
    '',
    'ACTIONABLE IMPROVEMENT SUGGESTIONS',
    '----------------------------------',
    ...result.improvement_suggestions.map((step, idx) => `${idx + 1}. ${step}`),
    '',
    'OPTIMIZED PROFESSIONAL SUMMARY',
    '------------------------------',
    result.optimized_summary,
    '',
    'LIKELY INTERVIEW QUESTIONS',
    '--------------------------',
    ...result.interview_questions.map((q, idx) => `${idx + 1}. ${q}`),
    '',
    'Generated by ResumeRank AI | Hybrid NLP + LLM Approach',
  ];

  return lines.join('\n');
}
